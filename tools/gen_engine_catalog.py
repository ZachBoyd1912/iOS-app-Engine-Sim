#!/usr/bin/env python3
"""Generate EngineCatalogData.swift from docs/research/raw/engines.md.

The research file is the single source of truth. It states a firing order only where a source
gives one, marks derived values, and leaves the rest unsourced. This script preserves that
provenance exactly and never fills a gap with a guess.

Run from the repo root:  python tools/gen_engine_catalog.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "research" / "raw" / "engines.md"
OUT = ROOT / "Native" / "PistonForgeKit" / "Sources" / "PistonForgeKit" / "Catalog" / "EngineCatalogData.swift"

TAG = re.compile(r"\[[^\]]*\]")
CC = re.compile(r"([\d,]{2,})\s*cc", re.IGNORECASE)


def clean(text: str) -> str:
    return " ".join(TAG.sub("", text).split())


def swift_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse():
    rows = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 14:
            continue
        if not re.fullmatch(r"\d{2}", cells[0]):
            continue

        ident, name, cyl, layout, crank, firing = cells[0], cells[1], cells[2], cells[3], cells[4], cells[5]
        displacement, sources = cells[7], cells[13]

        try:
            cylinders = int(re.sub(r"[^\d]", "", cyl) or "0")
        except ValueError:
            cylinders = 0

        raw = clean(firing)
        low = raw.lower()
        if low.startswith("n/a") or low.startswith("not applicable"):
            firing_order, provenance = None, "notApplicable"
        elif low.startswith("not sourced") or low in ("", "unverified", "none"):
            firing_order, provenance = None, "unsourced"
        elif "derived" in low:
            firing_order, provenance = raw, "derived"
        else:
            firing_order, provenance = raw, "sourced"

        match = CC.search(displacement)
        cc = int(match.group(1).replace(",", "")) if match else None

        rows.append(dict(id=ident, name=clean(name), cylinders=cylinders, layout=clean(layout),
                         crank=clean(crank), firing=firing_order, provenance=provenance,
                         cc=cc, sources=clean(sources)))

    return rows


def emit(rows) -> str:
    lines = [
        "// Generated by tools/gen_engine_catalog.py from docs/research/raw/engines.md.",
        "// Do not edit by hand; edit the research file and re-run the generator.",
        "// Provenance is preserved from the source: .unsourced rows carry no firing order.",
        "",
        "extension EngineCatalog {",
        "    public static let all: [EngineCatalogEntry] = [",
    ]
    for r in rows:
        firing = "nil" if r["firing"] is None else swift_string(r["firing"])
        cc = "nil" if r["cc"] is None else str(r["cc"])
        lines.append(
            "        EngineCatalogEntry(id: {}, name: {}, cylinders: {}, layout: {}, crank: {}, "
            "firingOrder: {}, firingSource: .{}, displacementCc: {}, sources: {}),".format(
                swift_string(r["id"]), swift_string(r["name"]), r["cylinders"],
                swift_string(r["layout"]), swift_string(r["crank"]), firing,
                r["provenance"], cc, swift_string(r["sources"]))
        )
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main():
    rows = parse()
    if not rows:
        sys.exit("no rows parsed from engines.md")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(rows), encoding="utf-8")
    counts = {}
    for r in rows:
        counts[r["provenance"]] = counts.get(r["provenance"], 0) + 1
    print(f"wrote {OUT.relative_to(ROOT)} with {len(rows)} rows")
    print("provenance:", counts)


if __name__ == "__main__":
    main()
